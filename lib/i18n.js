const SKIP = new Set(['svg', 'path', 'circle', 'rect', 'g', 'line', 'polyline', 'polygon', 'ellipse', 'text', 'tspan', 'defs', 'style', 'script', 'canvas', 'textarea', 'input', 'option']);
const ATTRS = ['aria-label', 'title', 'placeholder', 'alt'];

function word(s) {
  if (typeof s !== 'string' || !/[A-Za-z]/.test(s)) return s;
  if (BN[s] !== undefined) return BN[s];
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  return m && BN[m[2]] !== undefined ? m[1] + BN[m[2]] + m[3] : s;
}

export function tr(lang, s) { return lang === 'bn' ? word(s) : s; }

function walk(node) {
  if (typeof node === 'string') return word(node);
  if (Array.isArray(node)) return node.map(walk);
  if (!node || typeof node !== 'object' || !node.props) return node;
  if (typeof node.type === 'string' && SKIP.has(node.type)) return node;
  if (node.props['data-noi18n']) return node;
  const change = {};
  for (const a of ATTRS) if (typeof node.props[a] === 'string') { const w = word(node.props[a]); if (w !== node.props[a]) change[a] = w; }
  if (node.props.children !== undefined) change.children = walk(node.props.children);
  return React.cloneElement(node, change);
}

// Swap English text for Bangla across a finished page.
export function localize(tree, lang) { return lang === 'bn' ? walk(tree) : tree; }
